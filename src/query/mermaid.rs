    #[test]
    fn render_emits_dotted_annotated_edge() {
        // Trigger workflow has a step-anchored Dispatches annotation pointing
        // at a workflow_call-only target. The mermaid output must include the
        // dotted `-. dispatches .->` edge plus the classDef declaration.
        let trigger = wf(
            ".github/workflows/trigger.yml",
            Some("Trigger"),
            vec![TriggerSpec::bare(EventKind::Push)],
            vec![{
                let mut j = job_with(
                    "run",
                    ".github/workflows/trigger.yml",
                    None,
                    vec![step(0, None)],
                );
                j.steps[0].annotations.push(Annotation {
                    verb: AnnotationVerb::Dispatches,
                    resolution: AnnotationResolution::Resolved {
                        target: WorkflowId(".github/workflows/target.yml".into()),
                    },
                    source_line: 6,
                });
                j
            }],
        );
        let target = wf(
            ".github/workflows/target.yml",
            Some("Target"),
            vec![TriggerSpec::bare(EventKind::WorkflowCall)],
            vec![],
        );
        let ir = Ir {
            schema_version: 1,
            root: PathBuf::from("/tmp/test"),
            workflows: vec![trigger, target],
            actions: vec![],
            external_actions: vec![],
        };
        let out = render(&ir, None);
        assert!(
            out.contains("-. dispatches .->"),
            "expected dotted annotated edge, got:\n{out}"
        );
        assert!(
            out.contains("classDef ravelactAnnotation"),
            "expected classDef directive, got:\n{out}"
        );
        // target.yml must be canonical-declared in the graph
        assert!(
            out.contains(".github/workflows/target.yml"),
            "annotation target should appear as a node, got:\n{out}"
        );
    }
