#[derive(Debug)]
enum NodeRef {
    Workflow(String),
    Action(String),
}

#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
struct ExtKey {
    owner: String,
    repo: String,
    subpath: Option<String>,
    gitref: String,
}

impl ExtKey {
    fn from_action_ref(e: &ExternalActionRef) -> Self {
        ExtKey {
            owner: e.owner.clone(),
            repo: e.repo.clone(),
            subpath: e.subpath.clone(),
            gitref: e.gitref.clone(),
        }
    }
}

/// Key for a cross-repo reusable workflow node (`uses: owner/repo/.github/workflows/X.yml@ref`).
/// Distinct from [`ExtKey`] which identifies external *action* steps.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
struct ExtWfKey {
    owner: String,
    repo: String,
    /// Full path within the repo, e.g. `.github/workflows/deploy.yml`.
    path: String,
    gitref: String,
}

/// Key for a Docker container action ref (`uses: docker://[host/]image[:tag]`).
/// Mirrors `ExtKey` for the canonical-node + edge rendering path; uniqueness
/// comes from the full (host, image, tag) tuple so registry-distinct images
/// remain distinct nodes in the rendered graph.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
struct DockerKey {
    host: Option<String>,
    image: String,
    tag: Option<String>,
}

impl DockerKey {
    fn from_docker_ref(d: &DockerRef) -> Self {
        DockerKey {
            host: d.host.clone(),
            image: d.image.clone(),
            tag: d.tag.clone(),
        }
    }

    /// Reuse `DockerRef::display_str()` so `graph` and `trace` cannot drift on
    /// Docker label format (`{host/}{image}{:tag}`).
    fn display_str(&self) -> String {
        DockerRef {
            host: self.host.clone(),
            image: self.image.clone(),
            tag: self.tag.clone(),
        }
        .display_str()
    }
}

fn matches_scope(t: &TriggerSpec, scope: Option<&str>) -> bool {
    if !t.is_entry_point() {
        return false;
    }
    match scope {
        Some(e) => t.event_name() == e,
        None => true,
    }
}

/// Resolve one outgoing edge produced by [`for_each_outgoing_edge`] to a
/// target alias string in the rendered graph, gated by reachability sets so
/// orphan targets (uses-of-uses that the BFS never touched) are dropped.
/// Edges that never carry a structural target — annotation edges, dangling
/// resolutions — return `None`.
#[allow(clippy::too_many_arguments)]
fn resolve_structural_edge_target(
    edge: &Edge<'_>,
    reachable_wf: &HashSet<String>,
    reachable_act: &HashSet<String>,
    reachable_ext: &HashSet<ExtKey>,
    reachable_dock: &HashSet<DockerKey>,
    reachable_extwf: &HashSet<ExtWfKey>,
    wf_id: &HashMap<&str, String>,
    act_id: &HashMap<&str, String>,
    ext_id: &BTreeMap<ExtKey, String>,
    dock_id: &BTreeMap<DockerKey, String>,
    extwf_id: &BTreeMap<ExtWfKey, String>,
) -> Option<String> {
    match edge {
        Edge::Annotation(_) => None,
        Edge::CallsWorkflow(call) => match &call.workflow_ref {
            WorkflowRef::Local(t) => {
                if reachable_wf.contains(&t.0) {
                    Some(wf_id[t.0.as_str()].clone())
                } else {
                    None
                }
            }
            WorkflowRef::External {
                owner,
                repo,
                path,
                gitref,
            } => {
                let key = ExtWfKey {
                    owner: owner.clone(),
                    repo: repo.clone(),
                    path: path.clone(),
                    gitref: gitref.clone(),
                };
                if reachable_extwf.contains(&key) {
                    Some(extwf_id[&key].clone())
                } else {
                    None
                }
            }
        },
        Edge::Uses(uses) => match uses {
            UsesRef::LocalWorkflow(t) => {
                if reachable_wf.contains(&t.0) {
                    Some(wf_id[t.0.as_str()].clone())
                } else {
                    None
                }
            }
            UsesRef::LocalAction(t) => {
                if reachable_act.contains(&t.0) {
                    Some(act_id[t.0.as_str()].clone())
                } else {
                    None
                }
            }
            UsesRef::External {
                owner,
                repo,
                subpath,
                gitref,
            } => {
                let key = ExtKey {
                    owner: owner.clone(),
                    repo: repo.clone(),
                    subpath: subpath.clone(),
                    gitref: gitref.clone(),
                };
                if reachable_ext.contains(&key) {
                    Some(ext_id[&key].clone())
                } else {
                    None
                }
            }
            UsesRef::Docker(d) => {
                let key = DockerKey::from_docker_ref(d);
                if reachable_dock.contains(&key) {
                    Some(dock_id[&key].clone())
                } else {
                    None
                }
            }
        },
    }
}

fn sanitize_trigger_id(s: &str) -> String {
    s.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect()
}

fn escape_label(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '"' => out.push_str("#quot;"),
            '<' => out.push_str("#lt;"),
            '>' => out.push_str("#gt;"),
            ']' => out.push_str("&#93;"),
            '\n' => out.push_str("<br/>"),
            _ => out.push(c),
        }
    }
    out
}

fn workflow_label(wf: &Workflow) -> String {
    match &wf.name {
        Some(n) => format!("{}<br/>{}", escape_label(&wf.id.0), escape_label(n)),
        None => escape_label(&wf.id.0),
    }
}

fn local_action_label(c: &LocalAction) -> String {
    match &c.name {
        Some(n) => format!("{}<br/>{}", escape_label(&c.id.0), escape_label(n)),
        None => escape_label(&c.id.0),
    }
}

fn external_label(k: &ExtKey) -> String {
    let sub = k
        .subpath
        .as_deref()
        .map(|s| format!("/{s}"))
        .unwrap_or_default();
    escape_label(&format!("{}/{}{}@{}", k.owner, k.repo, sub, k.gitref))
}

fn external_wf_label(k: &ExtWfKey) -> String {
    escape_label(&format!("{}/{}/{}@{}", k.owner, k.repo, k.path, k.gitref))
}

fn emit_subgraph(
    out: &mut String,
    event: &str,
    rows: &[(String, String)],
    wf_lookup: &HashMap<&str, &Workflow>,
    overlay: Option<&GraphOverlay>,
    node_styles: &mut Vec<(String, String)>,
) {
    let id = sanitize_trigger_id(event);
    out.push_str(&format!("subgraph {id}\n"));
    for (wf_id_str, alias) in rows {
        let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
        let node_overlay = overlay.and_then(|o| o.workflows.get(wf_id_str.as_str()));
        out.push_str(&format!(
            "  {alias}[\"{}\"]\n",
            with_badge(workflow_label(wf), node_overlay)
        ));
        if let Some(o) = node_overlay {
            if !o.style.is_empty() {
                node_styles.push((alias.clone(), o.style.clone()));
            }
        }
    }
    out.push_str("end\n");
}

