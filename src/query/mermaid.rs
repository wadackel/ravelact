use crate::ir::*;
use crate::query::walk::{for_each_outgoing_edge, Edge, Node};
use crate::query::workflow_run as wr;
use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet, VecDeque};

/// External-finding overlay for `graph --highlight findings`, keyed by node id.
///
/// Built by `cmd_graph` from the M1 pipeline; the renderer consumes only plain
/// strings (a compact count badge + a Mermaid `style` body) so the query layer
/// stays decoupled from the CLI overlay types. Nodes absent from the maps
/// render exactly as before.
#[derive(Debug, Default)]
pub struct GraphOverlay {
    pub workflows: HashMap<String, GraphNodeOverlay>,
    pub actions: HashMap<String, GraphNodeOverlay>,
}

/// Per-node overlay: `badge` is appended to the node label (`<br/>H:2 M:1`);
/// `style` is the Mermaid `style <id> <style>` body (e.g. `fill:#…,stroke:#…`).
#[derive(Debug, Default, Clone)]
pub struct GraphNodeOverlay {
    pub badge: String,
    pub style: String,
}

/// Append a count badge to a node label as a `<br/>`-separated line.
fn with_badge(label: String, overlay: Option<&GraphNodeOverlay>) -> String {
    match overlay {
        Some(o) if !o.badge.is_empty() => format!("{label}<br/>{}", escape_label(&o.badge)),
        _ => label,
    }
}

const KNOWN_TRIGGER_ORDER: &[&str] = &[
    "push",
    "pull_request",
    "schedule",
    "workflow_dispatch",
    "workflow_run",
];

/// Render an IR as a Mermaid `graph LR` document.
///
/// `scope` filters entry-point workflows to those matching the given event.
/// When `scope` is `Some(event)` and zero entry-points match, the body is a
/// single `%% (no entry-point matches event <event>)` comment so callers
/// always see a parseable Mermaid v10+ document with the expected header.
//
// `collapsible_match` would collapse `Some(UsesRef::X(t)) => { if guard { ... } }`
// arms into guarded patterns, but doing so would force a `_ => {}` catch-all and
// lose exhaustiveness checking against future `UsesRef` variants.
#[allow(clippy::collapsible_match)]
pub fn render(ir: &Ir, scope: Option<&str>) -> String {
    render_impl(ir, scope, None)
}

/// `render` with a `--highlight findings` overlay: node labels gain a finding
/// count badge and findings-bearing nodes get a severity-colored `style`.
#[allow(clippy::collapsible_match)]
pub fn render_with_findings(ir: &Ir, scope: Option<&str>, overlay: &GraphOverlay) -> String {
    render_impl(ir, scope, Some(overlay))
}

#[allow(clippy::collapsible_match)]
fn render_impl(ir: &Ir, scope: Option<&str>, overlay: Option<&GraphOverlay>) -> String {
    let mut out = String::new();
    // Collected `style <id> <body>` lines for findings-bearing nodes, emitted
    // at graph level after all nodes/edges (style inside `subgraph` is invalid).
    let mut node_styles: Vec<(String, String)> = Vec::new();
    out.push_str("%% generated by ravelact\n");
    out.push_str("graph LR\n");

    // -- ID maps (sorted) ----------------------------------------------------
    let mut wf_sorted: Vec<&Workflow> = ir.workflows.iter().collect();
    wf_sorted.sort_by(|a, b| a.id.0.cmp(&b.id.0));
    let wf_id: HashMap<&str, String> = wf_sorted
        .iter()
        .enumerate()
        .map(|(n, wf)| (wf.id.0.as_str(), format!("wf_{n}")))
        .collect();

    let mut act_sorted: Vec<&LocalAction> = ir.actions.iter().collect();
    act_sorted.sort_by(|a, b| a.id.0.cmp(&b.id.0));
    let act_id: HashMap<&str, String> = act_sorted
        .iter()
        .enumerate()
        .map(|(n, c)| (c.id.0.as_str(), format!("act_{n}")))
        .collect();

    let mut ext_keys_sorted: BTreeSet<ExtKey> = BTreeSet::new();
    for e in &ir.external_actions {
        ext_keys_sorted.insert(ExtKey::from_action_ref(e));
    }
    let ext_id: BTreeMap<ExtKey, String> = ext_keys_sorted
        .iter()
        .enumerate()
        .map(|(n, k)| (k.clone(), format!("ext_{n}")))
        .collect();

    // -- Reachability BFS (orphans-style insert-before-enqueue) --------------
    let wf_lookup: HashMap<&str, &Workflow> =
        ir.workflows.iter().map(|w| (w.id.0.as_str(), w)).collect();
    let act_lookup: HashMap<&str, &LocalAction> =
        ir.actions.iter().map(|c| (c.id.0.as_str(), c)).collect();

    let mut reachable_wf: HashSet<String> = HashSet::new();
    let mut reachable_act: HashSet<String> = HashSet::new();
    let mut reachable_ext: HashSet<ExtKey> = HashSet::new();
    let mut reachable_dock: HashSet<DockerKey> = HashSet::new();
    let mut reachable_extwf: HashSet<ExtWfKey> = HashSet::new();
    let mut queue: VecDeque<NodeRef> = VecDeque::new();

    for wf in &ir.workflows {
        if wf.triggers.iter().any(|t| matches_scope(t, scope))
            && reachable_wf.insert(wf.id.0.clone())
        {
            queue.push_back(NodeRef::Workflow(wf.id.0.clone()));
        }
    }

    while let Some(node) = queue.pop_front() {
        let walk_node = match &node {
            NodeRef::Workflow(id) => wf_lookup.get(id.as_str()).copied().map(Node::Workflow),
            NodeRef::Action(id) => act_lookup.get(id.as_str()).copied().map(Node::Action),
        };
        let Some(walk_node) = walk_node else {
            continue;
        };
        for_each_outgoing_edge(walk_node, |ctx| match ctx.edge {
            Edge::Annotation(ann) => {
                if let AnnotationResolution::Resolved { target } = &ann.resolution {
                    if reachable_wf.insert(target.0.clone()) {
                        queue.push_back(NodeRef::Workflow(target.0.clone()));
                    }
                }
            }
            Edge::CallsWorkflow(call) => match &call.workflow_ref {
                WorkflowRef::Local(t) => {
                    if reachable_wf.insert(t.0.clone()) {
                        queue.push_back(NodeRef::Workflow(t.0.clone()));
                    }
                }
                WorkflowRef::External {
                    owner,
                    repo,
                    path,
                    gitref,
                } => {
                    reachable_extwf.insert(ExtWfKey {
                        owner: owner.clone(),
                        repo: repo.clone(),
                        path: path.clone(),
                        gitref: gitref.clone(),
                    });
                }
            },
            Edge::Uses(uses) => match uses {
                UsesRef::LocalWorkflow(t) => {
                    if reachable_wf.insert(t.0.clone()) {
                        queue.push_back(NodeRef::Workflow(t.0.clone()));
                    }
                }
                UsesRef::LocalAction(t) => {
                    if reachable_act.insert(t.0.clone()) {
                        queue.push_back(NodeRef::Action(t.0.clone()));
                    }
                }
                UsesRef::External {
                    owner,
                    repo,
                    subpath,
                    gitref,
                } => {
                    reachable_ext.insert(ExtKey {
                        owner: owner.clone(),
                        repo: repo.clone(),
                        subpath: subpath.clone(),
                        gitref: gitref.clone(),
                    });
                }
                UsesRef::Docker(d) => {
                    reachable_dock.insert(DockerKey::from_docker_ref(d));
                }
            },
        });
    }

    // Drop reachable ids that do not exist in the IR. These come from
    // dangling local `uses:` references (e.g. `uses: ./.github/actions/typo`).
    // Wiring surfaces them as `DanglingLocalUses` findings; the graph emits
    // a `%% unresolved` comment instead of panicking on the missing lookup.
    let mut unresolved_uses: BTreeSet<String> = BTreeSet::new();
    reachable_wf.retain(|id| {
        if wf_lookup.contains_key(id.as_str()) {
            true
        } else {
            unresolved_uses.insert(format!("local-workflow: {id}"));
            false
        }
    });
    reachable_act.retain(|id| {
        if act_lookup.contains_key(id.as_str()) {
            true
        } else {
            unresolved_uses.insert(format!("local-action: {id}"));
            false
        }
    });

    // Empty-scope short-circuit.
    if let Some(e) = scope {
        if reachable_wf.is_empty() {
            out.push_str(&format!("%% (no entry-point matches event {e})\n"));
            return out;
        }
    }

    // -- External workflow ID map (sorted; built from BFS reachability) -------
    let extwf_keys_sorted: BTreeSet<ExtWfKey> = reachable_extwf.iter().cloned().collect();
    let extwf_id: BTreeMap<ExtWfKey, String> = extwf_keys_sorted
        .iter()
        .enumerate()
        .map(|(n, k)| (k.clone(), format!("extwf_{n}")))
        .collect();

    // -- Docker container action ID map (sorted; built from BFS reachability) -
    let dock_keys_sorted: BTreeSet<DockerKey> = reachable_dock.iter().cloned().collect();
    let dock_id: BTreeMap<DockerKey, String> = dock_keys_sorted
        .iter()
        .enumerate()
        .map(|(n, k)| (k.clone(), format!("dock_{n}")))
        .collect();

    // -- Subgraphs (per-trigger aliases for entry-point workflows) -----------
    type EntryRow = (String, String); // (wf_id_str, alias_id)
    let mut sub_known: BTreeMap<usize, Vec<EntryRow>> = BTreeMap::new();
    let mut sub_other: BTreeMap<String, Vec<EntryRow>> = BTreeMap::new();

    for wf_id_str in &reachable_wf {
        let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
        for trigger in &wf.triggers {
            if !trigger.is_entry_point() {
                continue;
            }
            if let Some(s) = scope {
                if trigger.event_name() != s {
                    continue;
                }
            }
            let event = trigger.event_name();
            let suffix = sanitize_trigger_id(event);
            let alias = format!("{}__{}", wf_id[wf_id_str.as_str()], suffix);
            let row: EntryRow = (wf_id_str.clone(), alias);

            if let Some(idx) = KNOWN_TRIGGER_ORDER.iter().position(|x| *x == event) {
                sub_known.entry(idx).or_default().push(row);
            } else {
                sub_other.entry(event.to_string()).or_default().push(row);
            }
        }
    }
    for v in sub_known.values_mut() {
        v.sort_by(|a, b| a.1.cmp(&b.1));
    }
    for v in sub_other.values_mut() {
        v.sort_by(|a, b| a.1.cmp(&b.1));
    }

    // -- Canonical-needed determination --------------------------------------
    let mut canonical: HashSet<String> = HashSet::new();
    let mut pure_reusable: HashSet<String> = HashSet::new();
    for wf_id_str in &reachable_wf {
        let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
        let is_pure_reusable = !wf.triggers.iter().any(|t| t.is_entry_point())
            && wf
                .triggers
                .iter()
                .any(|t| t.event == EventKind::WorkflowCall);
        if is_pure_reusable {
            canonical.insert(wf_id_str.clone());
            pure_reusable.insert(wf_id_str.clone());
        }
    }
    // Annotation targets carried by reachable composite actions also become
    // canonical so the graph includes them even when no workflow-side `uses:`
    // structurally references them.
    for act_id_str in &reachable_act {
        let comp = act_lookup.get(act_id_str.as_str()).unwrap();
        for_each_outgoing_edge(Node::Action(comp), |ctx| {
            if let Edge::Annotation(ann) = ctx.edge {
                if let AnnotationResolution::Resolved { target } = &ann.resolution {
                    if reachable_wf.contains(&target.0) {
                        canonical.insert(target.0.clone());
                    }
                }
            }
        });
    }
    for wf_id_str in &reachable_wf {
        let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
        for_each_outgoing_edge(Node::Workflow(wf), |ctx| {
            let target_id: Option<&WorkflowId> = match ctx.edge {
                Edge::Annotation(ann) => match &ann.resolution {
                    AnnotationResolution::Resolved { target } => Some(target),
                    AnnotationResolution::Dangling { .. } => None,
                },
                Edge::CallsWorkflow(call) => match &call.workflow_ref {
                    WorkflowRef::Local(target) => Some(target),
                    WorkflowRef::External { .. } => None,
                },
                Edge::Uses(UsesRef::LocalWorkflow(target)) => Some(target),
                Edge::Uses(_) => None,
            };
            if let Some(target) = target_id {
                if reachable_wf.contains(&target.0) {
                    canonical.insert(target.0.clone());
                }
            }
        });
    }

    // -- workflow_run resolution --------------------------------------------
    // Use the query-layer name index (build_index) so both explicit `name:`
    // fields and path-based fallback names are resolved correctly.
    // Spec: workflow_run.workflows matches by display name; when `name:` is
    // absent the path acts as the effective name.
    // https://docs.github.com/en/actions/reference/workflows-and-actions/events-that-trigger-workflows
    let wr_name_index = wr::build_index(ir);
    let wr_trigger_idx = KNOWN_TRIGGER_ORDER
        .iter()
        .position(|x| *x == "workflow_run")
        .unwrap();
    let mut wr_edges: Vec<(String, String)> = Vec::new();
    let mut comments: BTreeSet<String> = BTreeSet::new();
    if let Some(rows) = sub_known.get(&wr_trigger_idx).cloned() {
        for (wf_id_str, alias) in rows {
            let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
            for trigger in &wf.triggers {
                if let Some(EventExtras::WorkflowRun { workflows }) = &trigger.extras {
                    for upstream_name in workflows {
                        let targets = wr::resolve_name(&wr_name_index, upstream_name);
                        if targets.is_empty() {
                            comments.insert(format!("workflow_run unresolved: {upstream_name}"));
                        } else {
                            for upstream_id in targets {
                                if reachable_wf.contains(&upstream_id.0) {
                                    wr_edges.push((upstream_id.0.clone(), alias.clone()));
                                    canonical.insert(upstream_id.0.clone());
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    // -- Emit subgraphs ------------------------------------------------------
    for (idx, rows) in &sub_known {
        let event = KNOWN_TRIGGER_ORDER[*idx];
        emit_subgraph(&mut out, event, rows, &wf_lookup, overlay, &mut node_styles);
    }
    for (event, rows) in &sub_other {
        emit_subgraph(&mut out, event, rows, &wf_lookup, overlay, &mut node_styles);
    }

    // -- Emit canonical workflow declarations --------------------------------
    let mut canon_list: Vec<&String> = canonical.iter().collect();
    canon_list.sort_by(|a, b| wf_id[a.as_str()].cmp(&wf_id[b.as_str()]));
    for wf_id_str in canon_list {
        let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
        let node_overlay = overlay.and_then(|o| o.workflows.get(wf_id_str.as_str()));
        let node_id = &wf_id[wf_id_str.as_str()];
        out.push_str(&format!(
            "{}[\"{}\"]\n",
            node_id,
            with_badge(workflow_label(wf), node_overlay)
        ));
        if let Some(o) = node_overlay {
            if !o.style.is_empty() {
                node_styles.push((node_id.clone(), o.style.clone()));
            }
        }
    }

    // -- Composites (reachable only, sorted) ---------------------------------
    let mut act_list: Vec<&String> = reachable_act.iter().collect();
    act_list.sort_by(|a, b| act_id[a.as_str()].cmp(&act_id[b.as_str()]));
    for act_id_str in act_list {
        let c = act_lookup.get(act_id_str.as_str()).unwrap();
        let node_overlay = overlay.and_then(|o| o.actions.get(act_id_str.as_str()));
        let node_id = &act_id[act_id_str.as_str()];
        out.push_str(&format!(
            "{}[\"{}\"]\n",
            node_id,
            with_badge(local_action_label(c), node_overlay)
        ));
        if let Some(o) = node_overlay {
            if !o.style.is_empty() {
                node_styles.push((node_id.clone(), o.style.clone()));
            }
        }
    }

    // -- Externals (reachable only, sorted) ----------------------------------
    let mut ext_list: Vec<&ExtKey> = reachable_ext.iter().collect();
    ext_list.sort();
    for k in ext_list {
        out.push_str(&format!("{}[\"{}\"]\n", ext_id[k], external_label(k)));
    }

    // -- Docker container actions (reachable only, sorted) -------------------
    for k in &dock_keys_sorted {
        out.push_str(&format!(
            "{}[\"{}\"]\n",
            dock_id[k],
            escape_label(&k.display_str())
        ));
    }

    // -- External workflows (reachable only, sorted) -------------------------
    let mut extwf_list: Vec<&ExtWfKey> = reachable_extwf.iter().collect();
    extwf_list.sort();
    for k in extwf_list {
        out.push_str(&format!("{}[\"{}\"]\n", extwf_id[k], external_wf_label(k)));
    }

    // -- Comments (sorted) ---------------------------------------------------
    for c in &comments {
        out.push_str(&format!("%% {c}\n"));
    }
    for c in &unresolved_uses {
        out.push_str(&format!("%% unresolved {c}\n"));
    }

    // -- Edges ---------------------------------------------------------------
    let mut edges: BTreeSet<(String, String, Option<String>)> = BTreeSet::new();

    let collect_outgoing =
        |source: &str, wf: &Workflow, edges: &mut BTreeSet<(String, String, Option<String>)>| {
            for_each_outgoing_edge(Node::Workflow(wf), |ctx| {
                let target_alias = resolve_structural_edge_target(
                    &ctx.edge,
                    &reachable_wf,
                    &reachable_act,
                    &reachable_ext,
                    &reachable_dock,
                    &reachable_extwf,
                    &wf_id,
                    &act_id,
                    &ext_id,
                    &dock_id,
                    &extwf_id,
                );
                if let Some(target) = target_alias {
                    edges.insert((source.to_string(), target, None));
                }
            });
        };

    // Edges from per-trigger aliases.
    for rows in sub_known.values() {
        for (wf_id_str, alias) in rows {
            let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
            collect_outgoing(alias, wf, &mut edges);
        }
    }
    for rows in sub_other.values() {
        for (wf_id_str, alias) in rows {
            let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
            collect_outgoing(alias, wf, &mut edges);
        }
    }

    // Edges from pure-reusable canonical (no entry-point trigger).
    for wf_id_str in &pure_reusable {
        let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
        collect_outgoing(&wf_id[wf_id_str.as_str()], wf, &mut edges);
    }

    // Edges from composites.
    for act_id_str in &reachable_act {
        let c = act_lookup.get(act_id_str.as_str()).unwrap();
        let source = act_id[act_id_str.as_str()].clone();
        for_each_outgoing_edge(Node::Action(c), |ctx| {
            let target_alias = resolve_structural_edge_target(
                &ctx.edge,
                &reachable_wf,
                &reachable_act,
                &reachable_ext,
                &reachable_dock,
                &reachable_extwf,
                &wf_id,
                &act_id,
                &ext_id,
                &dock_id,
                &extwf_id,
            );
            if let Some(target) = target_alias {
                edges.insert((source.clone(), target, None));
            }
        });
    }

    // workflow_run edges.
    for (upstream_id, downstream_alias) in &wr_edges {
        edges.insert((
            wf_id[upstream_id.as_str()].clone(),
            downstream_alias.clone(),
            Some("workflow_run".to_string()),
        ));
    }

    for (from, to, label) in &edges {
        match label {
            Some(l) => out.push_str(&format!("{from} -->|{l}| {to}\n")),
            None => out.push_str(&format!("{from} --> {to}\n")),
        }
    }

    // -- Annotated edges (dotted, with verb label) --------------------------
    // Emitted after structural edges so they overlay the same graph.
    let mut annotated: BTreeSet<(String, String, String)> = BTreeSet::new();

    let collect_annotated_outgoing =
        |source: &str, wf: &Workflow, out: &mut BTreeSet<(String, String, String)>| {
            for_each_outgoing_edge(Node::Workflow(wf), |ctx| {
                if let Edge::Annotation(ann) = ctx.edge {
                    if let AnnotationResolution::Resolved { target } = &ann.resolution {
                        if reachable_wf.contains(&target.0) {
                            out.insert((
                                source.to_string(),
                                wf_id[target.0.as_str()].clone(),
                                verb_label(ann.verb).to_string(),
                            ));
                        }
                    }
                }
            });
        };

    for rows in sub_known.values() {
        for (wf_id_str, alias) in rows {
            let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
            collect_annotated_outgoing(alias, wf, &mut annotated);
        }
    }
    for rows in sub_other.values() {
        for (wf_id_str, alias) in rows {
            let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
            collect_annotated_outgoing(alias, wf, &mut annotated);
        }
    }
    for wf_id_str in &pure_reusable {
        let wf = wf_lookup.get(wf_id_str.as_str()).unwrap();
        collect_annotated_outgoing(&wf_id[wf_id_str.as_str()], wf, &mut annotated);
    }

    // Composite-action annotated edges (manifest + per-step), originating from
    // the action node itself. Mirrors the workflow-side walk above so verbs
    // attached to composite carriers show as dotted edges in the graph.
    for act_id_str in &reachable_act {
        let comp = act_lookup.get(act_id_str.as_str()).unwrap();
        let source = act_id[act_id_str.as_str()].clone();
        for_each_outgoing_edge(Node::Action(comp), |ctx| {
            if let Edge::Annotation(ann) = ctx.edge {
                if let AnnotationResolution::Resolved { target } = &ann.resolution {
                    if reachable_wf.contains(&target.0) {
                        annotated.insert((
                            source.clone(),
                            wf_id[target.0.as_str()].clone(),
                            verb_label(ann.verb).to_string(),
                        ));
                    }
                }
            }
        });
    }

    if !annotated.is_empty() {
        for (from, to, label) in &annotated {
            out.push_str(&format!("{from} -. {label} .-> {to}\n"));
        }
        out.push_str("classDef ravelactAnnotation stroke:#dca,stroke-dasharray:5 5\n");
    }

    // -- Finding-overlay node styles (graph level, after all nodes) ----------
    node_styles.sort();
    for (id, style) in &node_styles {
        out.push_str(&format!("style {id} {style}\n"));
    }

    out
}

fn verb_label(v: AnnotationVerb) -> &'static str {
    match v {
        AnnotationVerb::Dispatches => "dispatches",
        AnnotationVerb::Triggers => "triggers",
    }
}

