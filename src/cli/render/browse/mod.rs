/// Shared axum state for `browse` handlers. Carries the IR plus the
/// canonicalized browse root so `/api/node` can emit file paths relative
/// to it. Both fields are `Arc` so the struct stays cheap to clone for
/// every request (axum clones `State` on each invocation).
#[derive(Clone)]
pub(crate) struct BrowseState {
    ir: Arc<Ir>,
    root: Arc<PathBuf>,
    findings_by_node: Arc<FindingsByNode>,
}

pub(in crate::cli) fn run(
    root: &Path,
    cache_mode: CacheMode,
    excludes: &GlobSet,
    port: Option<u16>,
    no_open: bool,
    findings: &[PathBuf],
) -> Result<()> {
    let ir = Arc::new(super::super::build_or_load(root, cache_mode, excludes)?);
    let repo_info = compute_repo_info(root);
    let findings_by_node = Arc::new(load_findings_by_node(&ir, findings)?);
    // Match the canonicalization that `discover_sources` (src/ir/build.rs)
    // applies to root when populating `SourcePos.file`. Holding the same
    // canonical form here means `strip_prefix` succeeds in the normal case;
    // the absolute fallback in `BrowseSvc::node_response` covers cache-loaded
    // IRs whose source paths point at a moved or renamed root.
    let canon_root = root
        .canonicalize()
        .with_context(|| format!("canonicalize browse root {}", root.display()))?;
    let state = BrowseState {
        ir,
        root: Arc::new(canon_root),
        findings_by_node,
    };

    // Multi-threaded runtime with one worker: ConnectRPC's tower stack
    // requires `Send + 'static` on response futures (see
    // `BrowseService::get_graph` trait bound), which `current_thread`
    // can't satisfy. A single worker preserves the original "single
    // local user, no parallelism" assumption.
    let runtime = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(1)
        .enable_all()
        .build()?;
    runtime.block_on(serve(state, repo_info, port, no_open))
}

/// Load every `--findings` file, run the M1 pipeline, and group the enriched
/// findings by IR node (owned, deterministically sorted). Empty map when no
/// findings were supplied — the browse overlay then stays inert.
fn load_findings_by_node(ir: &Ir, paths: &[PathBuf]) -> Result<FindingsByNode> {
    if paths.is_empty() {
        return Ok(FindingsByNode::new());
    }
    let enriched = findings_overlay::load_enriched(ir, paths)?;
    let grouped = findings_overlay::group_by_node(&enriched);
    Ok(grouped
        .into_iter()
        .map(|(key, refs)| (key, refs.into_iter().cloned().collect()))
        .collect())
}

fn build_graph_response(ir: &Ir, findings_by_node: &FindingsByNode) -> pb::GetGraphResponse {
    let mut b = GraphBuilder::new();

    // Initial nodes from IR collections. Anything reached via edge
    // traversal that is not in these collections is synthesised on the
    // fly (see GraphBuilder::ensure_*).
    for wf in &ir.workflows {
        let id = workflow_node_id(&wf.id);
        let label = wf.name.clone().unwrap_or_else(|| wf.id.0.clone());
        b.mark_workflow(&id);
        b.add_node(id, label, "workflow");
    }
    for la in &ir.actions {
        let id = action_node_id(&la.id);
        let label = la.name.clone().unwrap_or_else(|| la.id.0.clone());
        b.mark_local_action(&id);
        b.add_node(id, label, "local-action");
    }
    for ea in &ir.external_actions {
        let id = external_action_node_id(ea);
        b.mark_external_action(&id);
        b.add_node(id, external_action_label(ea), "external-action");
    }

    for wf in &ir.workflows {
        let source = workflow_node_id(&wf.id);
        b.visit(source, walk::Node::Workflow(wf));
    }
    for la in &ir.actions {
        let source = action_node_id(&la.id);
        b.visit(source, walk::Node::Action(la));
    }

    inject_findings_overlay(&mut b.nodes, &mut b.edges, ir, findings_by_node);

    pb::GetGraphResponse {
        nodes: b.nodes,
        edges: b.edges,
        __buffa_unknown_fields: Default::default(),
    }
}

/// Map a graph node id (`wf:` / `la:` prefixed) back to the [`NodeKey`] used
/// to index findings. External / docker nodes never carry findings → `None`.
fn graph_id_node_key(id: &str) -> Option<NodeKey> {
    if let Some(rest) = id.strip_prefix("wf:") {
        Some(NodeKey::Workflow(WorkflowId(rest.to_string())))
    } else {
        id.strip_prefix("la:")
            .map(|rest| NodeKey::Action(ActionId(rest.to_string())))
    }
}

/// Whether any finding on a node is reachable from a risky trigger.
fn node_reachable_from_risky(findings: &[EnrichedFinding]) -> bool {
    findings.iter().any(|ef| {
        ef.graph_context
            .reachable_from
            .iter()
            .any(|t| RISKY_TRIGGERS.contains(&t.as_str()))
    })
}

/// Whether any finding on a node sits on an orphan node.
fn node_is_orphan(findings: &[EnrichedFinding]) -> bool {
    findings.iter().any(|ef| ef.graph_context.is_orphan)
}

/// Distinct source-tool labels (e.g. `["zizmor"]`) across a node's findings,
/// sorted for deterministic output. Backs the SPA's source filter facet.
fn node_finding_sources(findings: &[EnrichedFinding]) -> Vec<String> {
    let mut sources: Vec<String> = findings
        .iter()
        .map(|ef| ef.finding.source.label().to_string())
        .collect();
    sources.sort();
    sources.dedup();
    sources
}

/// Whether any finding on a node has write-all or a sensitive write scope.
/// Always false for action nodes (no permission context in M1).
fn node_has_write(findings: &[EnrichedFinding]) -> bool {
    findings.iter().any(|ef| {
        ef.graph_context
            .permission_context
            .as_ref()
            .is_some_and(|pc| {
                pc.write_all
                    || pc
                        .write_scopes
                        .iter()
                        .any(|s| SENSITIVE_WRITE_SCOPES.contains(&s.as_str()))
            })
    })
}

/// Inject the findings overlay into the freshly built nodes/edges: per-node
/// source-severity counts + context flags, and the dangerous-path edge set.
fn inject_findings_overlay(
    nodes: &mut [pb::CyNode],
    edges: &mut [pb::CyEdge],
    ir: &Ir,
    findings_by_node: &FindingsByNode,
) {
    if findings_by_node.is_empty() {
        return;
    }

    // Per-node counts + context flags.
    for node in nodes.iter_mut() {
        let Some(data) = node.data.as_option_mut() else {
            continue;
        };
        let Some(key) = graph_id_node_key(&data.id) else {
            continue;
        };
        let Some(group) = findings_by_node.get(&key) else {
            continue;
        };
        let refs: Vec<&EnrichedFinding> = group.iter().collect();
        let counts = SeverityCounts::tally(&refs, Basis::Source);
        data.finding_counts = ::buffa::MessageField::some(severity_counts_to_proto(&counts));
        data.reachable_from_risky = node_reachable_from_risky(group);
        data.is_orphan = node_is_orphan(group);
        data.has_write = node_has_write(group);
        data.finding_sources = node_finding_sources(group);
    }

    // Dangerous-path edges: an edge u→v lies on a risky-entry→finding path iff
    // u is forward-reachable from a risky entry AND v is backward-reachable to
    // a finding node. Both closures run over the directed edge set.
    let finding_node_ids: HashSet<String> = findings_by_node
        .keys()
        .map(|k| match k {
            NodeKey::Workflow(id) => workflow_node_id(id),
            NodeKey::Action(id) => action_node_id(id),
        })
        .collect();
    let risky_entry_ids: HashSet<String> = ir
        .workflows
        .iter()
        .filter(|w| {
            w.triggers
                .iter()
                .any(|t| t.is_entry_point() && RISKY_TRIGGERS.contains(&t.event.name()))
        })
        .map(|w| workflow_node_id(&w.id))
        .collect();

    if finding_node_ids.is_empty() || risky_entry_ids.is_empty() {
        return;
    }

    let edge_pairs: Vec<(String, String)> = edges
        .iter()
        .filter_map(|e| {
            e.data
                .as_option()
                .map(|d| (d.source.clone(), d.target.clone()))
        })
        .collect();
    let forward = closure(&edge_pairs, &risky_entry_ids, Direction::Forward);
    let backward = closure(&edge_pairs, &finding_node_ids, Direction::Backward);

    for edge in edges.iter_mut() {
        if let Some(d) = edge.data.as_option_mut() {
            d.on_dangerous_path = forward.contains(&d.source) && backward.contains(&d.target);
        }
    }
}

enum Direction {
    Forward,
    Backward,
}

/// Reachability closure over directed edges from `seeds` (worklist traversal;
/// order is irrelevant to the resulting set). Forward follows source→target;
/// Backward follows target→source. Seeds are included in the result.
fn closure(edges: &[(String, String)], seeds: &HashSet<String>, dir: Direction) -> HashSet<String> {
    let mut adj: std::collections::HashMap<&str, Vec<&str>> = std::collections::HashMap::new();
    for (s, t) in edges {
        let (from, to) = match dir {
            Direction::Forward => (s.as_str(), t.as_str()),
            Direction::Backward => (t.as_str(), s.as_str()),
        };
        adj.entry(from).or_default().push(to);
    }
    let mut out: HashSet<String> = seeds.iter().cloned().collect();
    let mut queue: Vec<String> = seeds.iter().cloned().collect();
    while let Some(n) = queue.pop() {
        for &next in adj.get(n.as_str()).into_iter().flatten() {
            if out.insert(next.to_string()) {
                queue.push(next.to_string());
            }
        }
    }
    out
}

/// Convert the shared `SeverityCounts` tally into the proto message.
fn severity_counts_to_proto(c: &SeverityCounts) -> pb::FindingCounts {
    pb::FindingCounts {
        error: c.error,
        high: c.high,
        medium: c.medium,
        low: c.low,
        info: c.info,
        total: c.error + c.high + c.medium + c.low + c.info,
        __buffa_unknown_fields: Default::default(),
    }
}

struct GraphBuilder {
    nodes: Vec<pb::CyNode>,
    edges: Vec<pb::CyEdge>,
    seen_workflows: HashSet<String>,
    seen_local_actions: HashSet<String>,
    seen_external_actions: HashSet<String>,
    seen_external_workflows: HashSet<String>,
    seen_dockers: HashSet<String>,
    edge_counter: usize,
}

impl GraphBuilder {
    fn new() -> Self {
        Self {
            nodes: Vec::new(),
            edges: Vec::new(),
            seen_workflows: HashSet::new(),
            seen_local_actions: HashSet::new(),
            seen_external_actions: HashSet::new(),
            seen_external_workflows: HashSet::new(),
            seen_dockers: HashSet::new(),
            edge_counter: 0,
        }
    }

    fn add_node(&mut self, id: String, label: String, kind: &str) {
        self.nodes.push(pb::CyNode {
            data: ::buffa::MessageField::some(pb::CyNodeData {
                id,
                label,
                kind: kind.to_string(),
                // Findings overlay fields default to empty; populated by the
                // findings-aware build path (see build_graph_response).
                finding_counts: ::buffa::MessageField::none(),
                reachable_from_risky: false,
                is_orphan: false,
                has_write: false,
                finding_sources: Vec::new(),
                __buffa_unknown_fields: Default::default(),
            }),
            __buffa_unknown_fields: Default::default(),
        });
    }

    fn mark_workflow(&mut self, id: &str) {
        self.seen_workflows.insert(id.to_string());
    }

    fn mark_local_action(&mut self, id: &str) {
        self.seen_local_actions.insert(id.to_string());
    }

    fn mark_external_action(&mut self, id: &str) {
        self.seen_external_actions.insert(id.to_string());
    }

    /// Cytoscape rejects edges whose endpoints do not match an existing node id,
    /// so we silently drop edges to targets that never made it into the node
    /// set. The same situation can arise for resolved annotations whose target
    /// workflow is excluded from the build, or `uses: ./...` references that
    /// `wiring` separately surfaces as `DanglingLocalUses`. The browse view is
    /// not the place to re-report those — it just stays well-formed.
    fn add_edge(&mut self, source: &str, target: String, kind: &str) {
        if !self.is_known_target(&target) {
            return;
        }
        let id = format!("e{}", self.edge_counter);
        self.edge_counter += 1;
        self.edges.push(pb::CyEdge {
            data: ::buffa::MessageField::some(pb::CyEdgeData {
                id,
                source: source.to_string(),
                target,
                kind: kind.to_string(),
                // Defaults to false; set by the findings-aware build path.
                on_dangerous_path: false,
                __buffa_unknown_fields: Default::default(),
            }),
            __buffa_unknown_fields: Default::default(),
        });
    }

    fn is_known_target(&self, id: &str) -> bool {
        self.seen_workflows.contains(id)
            || self.seen_local_actions.contains(id)
            || self.seen_external_actions.contains(id)
            || self.seen_external_workflows.contains(id)
            || self.seen_dockers.contains(id)
    }

    fn ensure_external_workflow(
        &mut self,
        owner: &str,
        repo: &str,
        path: &str,
        gitref: &str,
    ) -> String {
        let id = external_workflow_node_id(owner, repo, path, gitref);
        if self.seen_external_workflows.insert(id.clone()) {
            let label = format!("{owner}/{repo}/{path}@{gitref}");
            self.add_node(id.clone(), label, "external-workflow");
        }
        id
    }

    fn ensure_external_action(
        &mut self,
        owner: &str,
        repo: &str,
        subpath: Option<&str>,
        gitref: &str,
    ) -> String {
        let sub = subpath.map(|s| format!("/{s}")).unwrap_or_default();
        let id = format!("ea:{owner}/{repo}{sub}@{gitref}");
        if self.seen_external_actions.insert(id.clone()) {
            let label = format!("{owner}/{repo}{sub}@{gitref}");
            self.add_node(id.clone(), label, "external-action");
        }
        id
    }

    fn ensure_docker(&mut self, d: &crate::ir::DockerRef) -> String {
        let display = d.display_str();
        let id = docker_node_id(&display);
        if self.seen_dockers.insert(id.clone()) {
            self.add_node(id.clone(), display, "docker");
        }
        id
    }

    fn visit(&mut self, source: String, node: walk::Node<'_>) {
        walk::for_each_outgoing_edge(node, |ctx| match ctx.edge {
            walk::Edge::Annotation(ann) => {
                if let AnnotationResolution::Resolved { target } = &ann.resolution {
                    let tgt = workflow_node_id(target);
                    self.add_edge(&source, tgt, "annotation");
                }
            }
            walk::Edge::CallsWorkflow(call) => {
                let tgt = match &call.workflow_ref {
                    WorkflowRef::Local(wid) => workflow_node_id(wid),
                    WorkflowRef::External {
                        owner,
                        repo,
                        path,
                        gitref,
                    } => self.ensure_external_workflow(owner, repo, path, gitref),
                };
                self.add_edge(&source, tgt, "calls-workflow");
            }
            walk::Edge::Uses(uses) => {
                let (tgt, kind) = match uses {
                    UsesRef::LocalWorkflow(wid) => (workflow_node_id(wid), "uses-local-workflow"),
                    UsesRef::LocalAction(aid) => (action_node_id(aid), "uses-local-action"),
                    UsesRef::External {
                        owner,
                        repo,
                        subpath,
                        gitref,
                    } => (
                        self.ensure_external_action(owner, repo, subpath.as_deref(), gitref),
                        "uses-external-action",
                    ),
                    UsesRef::Docker(d) => (self.ensure_docker(d), "uses-docker"),
                };
                self.add_edge(&source, tgt, kind);
            }
        });
    }
}

fn workflow_node_id(id: &WorkflowId) -> String {
    format!("wf:{}", id.0)
}

fn action_node_id(id: &ActionId) -> String {
    format!("la:{}", id.0)
}

fn external_action_node_id(r: &ExternalActionRef) -> String {
    let sub = r
        .subpath
        .as_deref()
        .map(|s| format!("/{s}"))
        .unwrap_or_default();
    format!("ea:{}/{}{}@{}", r.owner, r.repo, sub, r.gitref)
}

fn external_action_label(r: &ExternalActionRef) -> String {
    let sub = r
        .subpath
        .as_deref()
        .map(|s| format!("/{s}"))
        .unwrap_or_default();
    format!("{}/{}{}@{}", r.owner, r.repo, sub, r.gitref)
}

// Centralize the `ew:` / `dk:` id format so the graph builder and
// downstream handlers (e.g. `/api/event-impact`) cannot drift.
fn external_workflow_node_id(owner: &str, repo: &str, path: &str, gitref: &str) -> String {
    format!("ew:{owner}/{repo}/{path}@{gitref}")
}

fn docker_node_id(display: &str) -> String {
    format!("dk:{display}")
}

