// `proto/ravelact/browse/v1/browse.proto`. The `proto` module carries
// buffa-generated message types; `connect` carries the `BrowseService`
// trait, the `BrowseServiceClient<T>` Rust client, and the
// router-registration glue. Both are `pub` so `tests/e2e_browse.rs`
// can drive the spawned server through the generated client. Both
